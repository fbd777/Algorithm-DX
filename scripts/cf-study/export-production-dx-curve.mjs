/** Generate the adopted analytic curve; never inherit validation from the old empirical model. */
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';

const sourceFile = 'results/cf-study/t97-production.json';
const source = await fs.readFile(sourceFile, 'utf8');
const c = JSON.parse(source);
const f = c.formula;
if (f.kind !== 'saturation-linear' ||
    ![f.originQ,f.baselineMinutes,f.slopeMinutesPerRating,f.gainMinutes,f.scaleRating].every(Number.isFinite) ||
    f.baselineMinutes <= 0 || f.scaleRating <= 0 || f.slopeMinutesPerRating < 0 || f.gainMinutes < 0) throw new Error('非法公式参数');
if (![c.fitMinQ,c.fitMaxQ,c.gridStepQ,c.calibrationMinQ,c.calibrationMaxQ].every(Number.isFinite) ||
    c.fitMinQ !== f.originQ || c.fitMaxQ < c.fitMinQ || c.gridStepQ !== 25 ||
    (c.fitMaxQ-c.fitMinQ)%c.gridStepQ !== 0 || c.calibrationMinQ < c.fitMinQ ||
    c.calibrationMaxQ > c.fitMaxQ || c.calibrationMaxQ < c.calibrationMinQ) throw new Error('非法曲线范围');
const seconds = q => {
  const delta = q-f.originQ;
  return 60*(f.baselineMinutes+f.slopeMinutesPerRating*delta-f.gainMinutes*Math.expm1(-delta/f.scaleRating));
};
const points = [];
for(let q=c.fitMinQ;q<=c.fitMaxQ;q+=c.gridStepQ) {
  const s=seconds(q);
  if(!Number.isFinite(s)||s<=0||(points.length && s<points.at(-1)[1])) throw new Error('曲线必须为有限正数且单调不降');
  points.push([q,s]);
}
const curve = {
  model:c.model, sourceFile, sourceSha256:createHash('sha256').update(source).digest('hex'),
  generatedAt:new Date().toISOString(), fitMinQ:c.fitMinQ, fitMaxQ:c.fitMaxQ, gridStepQ:c.gridStepQ,
  calibrationMinQ:c.calibrationMinQ, calibrationMaxQ:c.calibrationMaxQ,
  productionReady:Boolean(c.productionReady), productionReadyBasis:c.productionReadyBasis,
  formula:f, points,
};
const body = `/** Generated by scripts/cf-study/export-dx-curve.mjs; edit the source model, not this file.
 * Active range: ${c.fitMinQ}–${c.fitMaxQ}; calibration inputs: ${c.calibrationMinQ}–${c.calibrationMaxQ}.
 * Source: ${sourceFile}. productionReady records statistical validation, not whether this model is active.
 */
import type { DxCurve } from './types.ts';
export const DX_CURVE: DxCurve = ${JSON.stringify(curve,null,2)};
`;
await fs.writeFile('src/dx/curve.ts',body);
const table = [
  '# 当前正式 T97 曲线（800–3500）', '',
  '2026-10-06 经用户确认采用。800–2000 为七个旧曲线代表值的等权拟合，2000 以上为函数外推；正式启用不代表外推已经过独立数据验证。', '',
  `T97(q) = ${f.baselineMinutes} + ${f.slopeMinutesPerRating}(q−${f.originQ}) + ${f.gainMinutes} × [1−exp(−(q−${f.originQ})/${f.scaleRating})]（分钟）。`, '',
  '参数来源：[t97-production.json](t97-production.json)。实际评分直接求公式值，以下每 100 Rating 列一行。', '',
  '| Rating | T97（分钟） | 区域 |', '|---:|---:|---|',
];
for(let q=c.fitMinQ;q<=c.fitMaxQ;q+=100) table.push(`| ${q} | ${(seconds(q)/60).toFixed(2)} | ${q>c.calibrationMaxQ?'外推':'拟合输入范围内'} |`);
await fs.writeFile('results/cf-study/T97_PRODUCTION_TABLE.md',table.join('\n')+'\n');
console.log(JSON.stringify({sourceFile,range:[c.fitMinQ,c.fitMaxQ],points:points.length,productionReady:c.productionReady}));
